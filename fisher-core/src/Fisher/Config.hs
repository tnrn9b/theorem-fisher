-- | The bytes of @data/default-config.yaml@ (upstream's @DEFAULT_CONFIG@
-- dumped in its order).
defaultConfigYaml :: ByteString
securityComment, fallbackComment :: ByteString
defaultConfigYaml = $(makeRelativeToProject "data/default-config.yaml" >>= embedFile)
securityComment = $(makeRelativeToProject "data/security-comment.txt" >>= embedFile)
fallbackComment = $(makeRelativeToProject "data/fallback-comment.txt" >>= embedFile)

-- | Upstream's @DEFAULT_CONFIG@, generated by @tools/gen-defaults.py@.
defaultConfig :: Value
defaultConfig = case Y.decodeEither' defaultConfigYaml of
  Right v@(Object _) -> v
  Right _ -> error "data/default-config.yaml is not a mapping"
  Left e -> error ("data/default-config.yaml: " <> Y.prettyPrintParseException e)

-- | @_config_version@ of the defaults, 9 at the pinned upstream.
latestConfigVersion :: Int
latestConfigVersion =
  case lookupKey "_config_version" defaultConfig of
    Just (Number n) | Just i <- toBoundedInteger n -> i
    _ -> error "default config has no integer _config_version"

-- | A dotted path into a configuration, @getPath ["agent", "max_turns"]@.
getPath :: [Text] -> Value -> Maybe Value
getPath [] v = Just v
getPath (k : ks) v = lookupKey k v >>= getPath ks

-- | @fisher.lessons.auto_judged@: judged and self lessons promoted on
-- their counts instead of waiting for a pin. Only @true@ turns it on. One
-- reader for the mining pass, @fisher lessons@ and the web app's panel.
lessonsAutoJudged :: Value -> Bool
lessonsAutoJudged cfg = getPath ["fisher", "lessons", "auto_judged"] cfg == Just (Bool True)

-- | @fisher.smt.enabled@: the SMT tools are on unless the key is @false@.
smtEnabled :: Value -> Bool
smtEnabled cfg = getPath ["fisher", "smt", "enabled"] cfg /= Just (Bool False)

-- | @fisher.smt.solver@: @auto@ (z3, then cvc5), @z3@ or @cvc5@.
smtSolver :: Value -> Text
smtSolver cfg = case getPath ["fisher", "smt", "solver"] cfg of
  Just (String t) | not (T.null t) -> t
  _ -> "auto"

-- | @fisher.smt.timeout_secs@: the solver's time limit, 10 by default,
-- clamped to 1..60.
smtTimeoutSecs :: Value -> Int
smtTimeoutSecs cfg = case getPath ["fisher", "smt", "timeout_secs"] cfg of
  Just (Number n)
    | n >= 60 -> 60
    | n <= 1 -> 1
    | otherwise -> floor n
  _ -> 10

-- | @fisher.smt.query_tactic@: the name of the query tool, @smt_show@ by default.
smtQueryTactic :: Value -> Text
smtQueryTactic cfg = case getPath ["fisher", "smt", "query_tactic"] cfg of
  Just (String t) | not (T.null t) -> t
  _ -> "smt_show"

-- | @_deep_merge@: keys of the override win, and where both sides hold a
-- mapping the merge recurses, so a partial user section keeps the rest of
-- its defaults.
deepMerge :: Value -> Value -> Value
deepMerge (Object base) (Object over) = Object (KM.unionWith pick base over)
  where
    pick b o = case (b, o) of
      (Object _, Object _) -> deepMerge b o
      _ -> o
deepMerge _ over = over

asObject :: Maybe Value -> KM.KeyMap Value
asObject = \case
  Just (Object o) -> o
  _ -> KM.empty

-- | @_normalize_max_turns_config@: a root-level @max_turns@ moves under
-- @agent@ unless @agent@ already has one, and @agent.max_turns@ always ends
-- up set.
normalizeMaxTurns :: Value -> Value
normalizeMaxTurns (Object c) =
  let agent0 = asObject (KM.lookup "agent" c)
      agent1 = case KM.lookup "max_turns" c of
        Just mt | not (KM.member "max_turns" agent0) -> KM.insert "max_turns" mt agent0
        _ -> agent0
      dflt = fromMaybe Null (getPath ["agent", "max_turns"] defaultConfig)
      agent2 = if KM.member "max_turns" agent1 then agent1 else KM.insert "max_turns" dflt agent1
   in Object (KM.delete "max_turns" (KM.insert "agent" (Object agent2) c))
normalizeMaxTurns v = v

-- | The step @load_config@ applies to the user file before merging: a
-- root-level @max_turns@ fills @agent.max_turns@ when that is absent or
-- null, and the root key goes.
liftLegacyMaxTurns :: KM.KeyMap Value -> KM.KeyMap Value
liftLegacyMaxTurns u = case KM.lookup "max_turns" u of
  Nothing -> u
  Just mt ->
    let agent = asObject (KM.lookup "agent" u)
        agent' = case KM.lookup "max_turns" agent of
          Just v | v /= Null -> agent
          _ -> KM.insert "max_turns" mt agent
     in KM.delete "max_turns" (KM.insert "agent" (Object agent') u)

-- | Load the configuration under a given home. Returns the configuration and any warnings; upstream prints the same warning and falls back to the
-- defaults when the file cannot be read.
loadConfigAt :: FilePath -> IO (Value, [Text])
loadConfigAt home = do
  ensureFisherHomeAt home
  let path = configPathIn home
  exists <- doesFileExist path
  if not exists
    then pure (normalizeMaxTurns defaultConfig, [])
    else do
      decoded <- Y.decodeFileEither path
      pure $ case decoded of
        Left e -> fallback (T.pack (Y.prettyPrintParseException e))
        Right v
          | not (pyTruthy v) -> (normalizeMaxTurns defaultConfig, [])
          | Object u <- v -> (normalizeMaxTurns (deepMerge defaultConfig (Object (liftLegacyMaxTurns u))), [])
          | otherwise -> fallback "the file does not contain a mapping"
  where
    fallback why = (normalizeMaxTurns defaultConfig, ["Warning: Failed to load config: " <> why])

-- | 'loadConfigAt' on the active home, printing warnings as upstream does.
loadConfig :: IO Value
loadConfig = do
  home <- ensureFisherHome
  (cfg, warnings) <- loadConfigAt home
  mapM_ TIO.putStrLn warnings
  pure cfg

-- | The bytes @save_config@ writes: the normalized configuration, then the
-- commented-out security and fallback sections when those features are not
-- configured.
renderConfig :: Value -> ByteString
renderConfig = renderConfigWith [defaultKeyOrder]

-- | The key order of upstream's @DEFAULT_CONFIG@.
defaultKeyOrder :: KeyOrder
defaultKeyOrder = unsafePerformIO (keyOrderOf defaultConfigYaml)
{-# NOINLINE defaultKeyOrder #-}

-- | 'renderConfig' with keys laid out by the given orders, first first.
renderConfigWith :: [KeyOrder] -> Value -> ByteString
renderConfigWith orders cfg =
  let normalized = normalizeMaxTurns cfg
      sec = lookupKey "security" normalized
      needsSecurity = case sec of
        Just s | pyTruthy s -> maybe True (== Null) (lookupKey "redact_secrets" s)
        _ -> True
      fb = lookupKey "fallback_model" normalized
      needsFallback = case fb of
        Just f | pyTruthy f ->
          not (maybe False pyTruthy (lookupKey "provider" f) && maybe False pyTruthy (lookupKey "model" f))
        _ -> True
      extra = [securityComment | needsSecurity] <> [fallbackComment | needsFallback]
   in encodeOrdered orders normalized <> BS.concat extra

-- | The save: the configuration as given, keys in the defaults' order and
-- then the existing file's.
saveConfigAt :: FilePath -> Value -> IO ()
saveConfigAt home cfg = do
  ensureFisherHomeAt home
  let path = configPathIn home
  existing <- keyOrderOfFile path
  atomicWriteFile ".config_.tmp" path (renderConfigWith [defaultKeyOrder, existing] cfg)
  secureFile path

saveConfig :: Value -> IO ()
saveConfig cfg = do
  home <- ensureFisherHome
  saveConfigAt home cfg
