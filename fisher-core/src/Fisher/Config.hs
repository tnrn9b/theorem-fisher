-- | @config.yaml@ in the Fisher home: the defaults, the merge of a user
-- file over them, and the save. Ported from upstream @cli/config.py@ at the
-- commit in @UPSTREAM@.
--
-- Keys are written in upstream's order: the defaults' order, then the order
-- of the file being replaced for keys the defaults lack (where Python's
-- deep merge appends them).
module Fisher.Config
  ( defaultConfig
  , defaultConfigYaml
  , latestConfigVersion
  , deepMerge
  , normalizeMaxTurns
  , liftLegacyMaxTurns
  , loadConfigAt
  , loadConfig
  , saveConfigAt
  , saveConfig
  , renderConfig
  , renderConfigWith
  , defaultKeyOrder
  , getPath
  , lessonsAutoJudged
  , smtEnabled
  , smtSolver
  , smtTimeoutSecs
  , smtQueryTactic
  ) where

